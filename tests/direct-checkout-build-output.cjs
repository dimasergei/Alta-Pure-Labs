'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const read=f=>fs.readFileSync('public-build/'+f,'utf8');
for(const file of ['direct-checkout-client.js','account.js','storefront-v2.js','workspace-v2.js','native-pay.js','payment-options-public.js','admin-payments.js'])new vm.Script(read(file),{filename:file});
assert.match(read('account.html'),/direct-checkout-client\.js/);
assert.equal((read('account.html').match(/src="\/cart-reference\.js"/g)||[]).length,1,'Checkout must use the shared wallet-enabled cart');
assert.equal((read('account.html').match(/href="\/cart-reference\.css"/g)||[]).length,1,'Checkout must include the shared cart appearance');
assert.match(read('account.js'),/p==='\/checkout'/);
assert.match(read('account.js'),/AccountExperience\.rewards/);
assert.match(read('storefront-v2.js'),/\/checkout/);
assert.doesNotMatch(read('storefront-v2.js'),/Buy annual pass|checkout\?plan=/);
assert.doesNotMatch(read('storefront-v2.js'),/Request.*invoice|checkout is (?:currently )?paused|reviewed invoices/i);
assert.doesNotMatch(read('workspace-v2.js'),/Rewards redemption is not offered|redemption is not enabled/i);
assert.doesNotMatch(read('payment-options-public.js'),/Request invoice|REVIEWED INVOICES|checkout&/);
assert.match(read('cart-reference.js'),/BLACKFRIDAY15/);
assert.match(read('checkout-reference.js'),/data-nlx-remove-coupon/);
assert.match(read('pay.html'),/My orders/);
assert.doesNotMatch(read('account.html')+read('pay.html'),/src="\/marketing-analytics\.js"/);
const account=read('account.js'),context={URL,location:{origin:'https://altapurelabs.com'}};
vm.createContext(context);vm.runInContext(account.slice(account.indexOf('function safeCheckoutReturn'),account.indexOf('function consumeCheckoutReturn')),context);
assert.equal(context.safeCheckoutReturn('/checkout?plan=vip'),'/checkout?plan=vip');
assert.equal(context.safeCheckoutReturn('/account/membership'),'/account/membership');
assert.equal(context.safeCheckoutReturn('/checkout?plan=forged'),'/memberships');
assert.equal(context.safeCheckoutReturn('/checkout?plan=elite&period=annual'),'/checkout?plan=elite&period=annual');
assert.equal(context.safeCheckoutReturn('/checkout?balance=1'),'/checkout?balance=1');
assert.equal(context.safeCheckoutReturn('/pay.html?invoice=123'),'/pay.html?invoice=123');
for(const candidate of ['//evil.test','/\\evil.test','https://evil.test','/admin-orders.html','/%5cevil.test'])assert.equal(context.safeCheckoutReturn(candidate),null);
console.log('Built checkout routes, scripts, terms, wallet page and privacy checks passed');
